export function convertSeedItemsToCatalog(): CatalogItem[] {
  return INVOICE_SEEDED_ITEMS.map((item) => ({
    id: `inv-${item.num}`,
    sku: `ТОВ-${String(item.num).padStart(3, '0')}`,
    name: item.name,
    category: item.category,
    unit: item.unit,
    price: item.price,
    keywords: item.synonyms.split(',').map((s) => s.trim().toLowerCase()).filter(Boolean),
    stock: 100,
  }));
}

export function generateSeedTsv(): string {
  const header = ['Порядковый номер', 'Название', 'Слова-синонимы', 'Цена'].join('\t');
  const rows = INVOICE_SEEDED_ITEMS.map((item) =>
    [item.num, item.name, item.synonyms, item.price].join('\t')
  );
  return [header, ...rows].join('\n');
}

export function generateSeedCsv(): string {
  const header = '"Порядковый номер","Название","Слова-синонимы","Цена"';
  const rows = INVOICE_SEEDED_ITEMS.map((item) =>
    `"${item.num}","${item.name.replace(/"/g, '""')}","${item.synonyms.replace(/"/g, '""')}","${item.price}"`
  );
  return [header, ...rows].join('\n');
}
